import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

const src = readFileSync('app/components/canvas/CanvasChat.vue', 'utf8')
const page = readFileSync('app/pages/canvas/index.vue', 'utf8')
const workspace = readFileSync('app/components/canvas/CanvasWorkspace.vue', 'utf8')

describe('CanvasChat 剧本确认', () => {
  it('长材料先确认交付，确认后把正文落到文本节点', () => {
    expect(src).toContain('shouldOpenBrief')
    expect(src).toContain('startBrief(value)')
    expect(src).toContain('confirmBriefAsk')
    expect(src).toContain('confirmBriefDoc')
    expect(src).toContain('emit(\'insertText\'')
    expect(src).toContain('emit(\'insertImages\'')
    expect(src).toContain('emit(\'insertAudios\'')
    expect(src).toContain('emit(\'generateBrief\'')
    expect(src).toContain('emit(\'placeVideos\'')
    expect(src).toContain('emit(\'composeBrief\'')
    expect(src).toContain('looksLikeComposeReport')
    expect(src).toContain('runBriefCompose')
    expect(src).toContain('composePlaced')
    expect(src).toContain('pushGenerateCard')
    expect(src).toContain('pushVideoCard')
    expect(src).toContain('pushComposeCard')
    expect(src).toContain('briefPathOf')
    expect(src).toContain('briefNodeTitle')
    expect(workspace).toContain('linkBriefShotAnchors')
    expect(workspace).toContain('briefGroupNodes(\'shot\')')
    expect(workspace).toContain('shotHasVideo')
    expect(workspace).toContain('placeBriefVideos()')
    expect(workspace).toContain('generateBriefPlaced([\'video\'])')
    expect(workspace).toContain('sanitizeGraphForSave')
    expect(workspace).toContain('seen.has(url)')
    expect(workspace).toContain('beforeGenerate')
    expect(src).toContain('briefProps')
    expect(src).toContain('propImagePrompt')
    expect(src).toContain('briefScenes')
    expect(src).toContain('briefVoices')
    expect(src).toContain('plainChatPrompt')
    expect(src).toContain('canvasApi.chat.list')
    expect(src).toContain('canvasApi.chat.create')
    expect(src).toContain('canvasApi.chat.update')
    expect(src).not.toContain('startCrew(')
    expect(src).not.toContain('shouldStartCrew')
  })

  it('批量生成一条条跑，文案数字会填上', () => {
    expect(src).toContain('fillI18n')
    expect(workspace).toContain('briefGenerateTail')
    expect(workspace).toContain('fillI18n')
    const generate = readFileSync('app/composables/useCanvasGenerate.ts', 'utf8')
    expect(generate).toContain('已排队，上一条完成后开始')
    expect(generate).toContain('opts.waitTask')
    expect(generate).toContain('beforeGenerate')
  })

  it('生成跑完才出下一张卡，对话里写进度', () => {
    expect(src).toContain('runBriefGenerate')
    expect(src).toContain('afterStillsReady')
    expect(src).toContain('onDone')
    expect(src).toContain('generatingItem')
    expect(src).toContain('writeBriefProgress')
    expect(src).toContain('composeNeedVideos')
    expect(src).toContain('await runBriefGenerate(groups)')
    expect(src).toContain('await afterStillsReady')
    expect(src).toContain('await runBriefVideos')
    expect(page).toContain('opts?.onDone')
    expect(workspace).toContain('opts?.onProgress')
  })

  it('画布页接上出视频、合成和估价', () => {
    expect(page).toContain('@place-videos="onChatPlaceVideos"')
    expect(page).toContain('@compose-brief="onChatComposeBrief"')
    expect(page).toContain(':brief-quote="briefQuote"')
    expect(page).toContain('placeBriefVideos')
    expect(page).toContain('composeBrief')
    expect(page).toContain('estimateBriefPlaced')
  })

  it('点欢迎区技能只填草稿，不立刻发出去', () => {
    expect(src).toMatch(/function useSkill\(item: ChatSkill\) \{\s*startSkillDraft\(item\)/)
    expect(src).toContain('prompt: item.prompt || \'\'')
    expect(src).toMatch(/function startSkillDraft\(skill: ChatSkill\) \{[\s\S]*?agentAutoModel\.value = true/)
  })

  it('历史 Brief 规格跟当条消息走，Markdown 只在客户端渲染', () => {
    expect(src).toContain('function specChipsOf(')
    expect(src).toContain('function briefPromptLinesOf(')
    expect(src).toContain('specChipsOf(item)')
    expect(src).not.toContain('liveSpecChips')
    expect(src).toContain('<ClientOnly v-else-if="!item.error && item.text">')
    expect(src).toContain('canvas.chat.skill.ready')
    expect(src).toContain('canvas.chat.brief.shotName')
    expect(src).toContain('item.description || item.slug')
    expect(src).toContain('briefHistoryText(item.card, t)')
  })
})
